    log "Внимание: ucode -c недоступен, пропускаю проверку синтаксиса"
fi

if ! sh -n "$TMP_DIR/usr/bin/forkop-servicecheck" >/dev/null 2>&1; then
    fail "Синтаксическая ошибка в CLI - установка отменена, система не тронута."
