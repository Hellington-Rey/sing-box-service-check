    if ! ucode -c -o /dev/null "$TMP_DIR/usr/lib/forkop-servicecheck/probe.uc" >/dev/null 2>&1; then
        printf '\n'
        ucode -c -o /dev/null "$TMP_DIR/usr/lib/forkop-servicecheck/probe.uc" || true
